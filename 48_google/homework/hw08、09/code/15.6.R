# F 臨界值：F(715, 712) 在 1% 顯著水準
cv_exact <- qf(0.99, df1 = 715, df2 = 712)
cat(sprintf("F(715, 712) 在 1%% 顯著水準的臨界值 = %.4f\n", cv_exact))

# 大樣本近似比較：分子自由度固定為 715，分母趨近於無窮大
cv_inf <- qf(0.99, df1 = 715, df2 = Inf)
cat(sprintf("F(715, Inf) 在 1%% 顯著水準的臨界值 = %.4f\n", cv_inf))

# 常見近似參考值
cv_ref1 <- qf(0.99, df1 = 500, df2 = 500)
cv_ref2 <- qf(0.99, df1 = 1000, df2 = 1000)
cat(sprintf("\n參考：F(500, 500)   臨界值 = %.4f\n", cv_ref1))
cat(sprintf("參考：F(1000, 1000) 臨界值 = %.4f\n", cv_ref2))